// Bundle supabase/migrations/*.sql into src/lib/migrations.generated.ts so the server
// can migrate itself anywhere (Vercel functions do not ship the .sql files).
import fs from "node:fs";
import path from "node:path";
const dir = path.resolve(import.meta.dirname, "../../../supabase/migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const body = files.map((f) => `  { name: ${JSON.stringify(f)}, sql: ${JSON.stringify(fs.readFileSync(path.join(dir, f), "utf8"))} },`).join("\n");
fs.writeFileSync(
  path.resolve(import.meta.dirname, "../src/lib/migrations.generated.ts"),
  `// Generated by scripts/gen-migrations.mjs from supabase/migrations. Do not edit.\nexport const MIGRATIONS: { name: string; sql: string }[] = [\n${body}\n];\n`,
);
console.log(`Bundled ${files.length} migration(s).`);
